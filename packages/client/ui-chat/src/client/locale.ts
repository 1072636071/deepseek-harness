/**
 * Draw one playful phrase for the running-turn status line.
 * @param localeId - active locale id; only `zh`/`en` have a bucket, so other
 *   ids return undefined and the caller falls back to `chat.deepDiving`.
 * @param random - source in `[0, 1)`; defaults to `Math.random` in production,
 *   injectable for deterministic tests.
 * @returns one phrase, or undefined when the locale has no bucket.
 */
export function pickDeepDivingPhrase(
  localeId: LocaleId,
  random: () => number = Math.random,
): string | undefined {
  const bucket = localeId in deepDivingPool ? deepDivingPool[localeId as keyof DeepDivingPool] : undefined
  if (bucket === undefined || bucket.length === 0) return undefined
  const index = Math.min(bucket.length - 1, Math.floor(random() * bucket.length))
  return bucket[index]
}
